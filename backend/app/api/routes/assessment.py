def _get_case(db: Session, user: User, cid) -> AssessmentCase:
    """Resolve a case by opaque slug or numeric id, enforcing access control."""
    case: AssessmentCase | None = None
    if isinstance(cid, int):
        case = db.get(AssessmentCase, cid)
    elif isinstance(cid, str):
        s = cid.strip()
        if s.isdigit():
            case = db.get(AssessmentCase, int(s))
        else:
            case = db.scalar(select(AssessmentCase).where(AssessmentCase.slug == s))
    if not case:
        raise HTTPException(404, "Case not found")
    if case.owner_user_id == user.id or user.role == Role.super_admin:
        return case
    if user.role == Role.wing_admin and case.wing_id == user.wing_id:
        return case
    raise HTTPException(status.HTTP_403_FORBIDDEN, "Not authorised for this case")


def _case_out(c: AssessmentCase) -> dict:
    return {"id": c.id, "slug": c.slug, "title": c.title,
            "assessment_year": c.assessment_year, "pan": c.pan,
            "section": c.section, "status": c.status, "owner_user_id": c.owner_user_id,
            "created_at": c.created_at.isoformat() if c.created_at else None}


def _latest_run(db: Session, cid: int) -> AssessmentRun | None:
    return db.scalar(select(AssessmentRun).where(AssessmentRun.case_id == cid)
                     .order_by(desc(AssessmentRun.id)).limit(1))


def _run_out(r: AssessmentRun) -> dict:
    return {"id": r.id, "case_id": r.case_id, "status": r.status, "progress": r.progress,
            "provider": r.provider, "model": r.model, "error": r.error}


def _out(o: AssessmentOutput) -> dict:
    return {"id": o.id, "kind": o.kind, "seq": o.seq, "label": o.label, "content": o.content,
            "citations": o.citations or [], "edited": o.edited, "version": o.version}


def _latest_outputs(db: Session, run_id: int) -> list[AssessmentOutput]:
    best: dict[tuple, AssessmentOutput] = {}
    for o in db.scalars(select(AssessmentOutput).where(AssessmentOutput.run_id == run_id)):
        key = (o.kind, o.seq)
        if key not in best or o.version > best[key].version:
            best[key] = o
    return list(best.values())


