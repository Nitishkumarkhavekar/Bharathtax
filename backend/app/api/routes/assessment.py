@router.post("/cases")
def create_case(body: CaseCreate, p: Principal = Depends(get_principal), db: Session = Depends(get_db)):
    import uuid as _uuid
    slug = _uuid.uuid4().hex
    c = AssessmentCase(owner_user_id=p.user.id, wing_id=p.user.wing_id, title=body.title,
                       assessment_year=body.assessment_year, pan=body.pan,
                       section=body.section, slug=slug)
    db.add(c); db.commit(); db.refresh(c)
    return _case_out(c)


@router.get("/cases")
def list_cases(p: Principal = Depends(get_principal), db: Session = Depends(get_db)):
    q = select(AssessmentCase).order_by(desc(AssessmentCase.updated_at))
    if p.user.role == Role.super_admin:
        pass
    elif p.user.role == Role.wing_admin:
        q = q.where(AssessmentCase.wing_id == p.user.wing_id)
    else:
        q = q.where(AssessmentCase.owner_user_id == p.user.id)

    # Self-heal a stranded 'running' badge whose latest run is already terminal.
    stuck = list(db.scalars(
        select(AssessmentCase.id).where(
            AssessmentCase.status == "running",
            *([] if p.user.role == Role.super_admin
              else [AssessmentCase.wing_id == p.user.wing_id] if p.user.role == Role.wing_admin
              else [AssessmentCase.owner_user_id == p.user.id]),
        )
    ))
    if stuck:
        from sqlalchemy import text as _sql_text
        try:
            db.execute(_sql_text("""
                UPDATE assessment_cases c
                   SET status = CASE
                                  WHEN r.status = 'done'  THEN 'ready'
                                  WHEN r.status = 'error' THEN 'error'
                                  ELSE c.status
                                END
                  FROM (
                    SELECT DISTINCT ON (case_id) case_id, status
                      FROM assessment_runs
                      WHERE case_id = ANY(:ids)
                      ORDER BY case_id, id DESC
                  ) r
                 WHERE r.case_id = c.id
                   AND c.status = 'running'
                   AND r.status IN ('done', 'error')
            """), {"ids": stuck})
            db.commit()
        except Exception:
            db.rollback()

    return [_case_out(c) for c in db.scalars(q)]


@router.get("/cases/{cid}")
def get_case(cid: str, p: Principal = Depends(get_principal), db: Session = Depends(get_db)):
    case = _get_case(db, p.user, cid)
    return {**_case_out(case),
            "documents": [{"id": d.id, "filename": d.filename, "category": d.category, "pages": d.pages}
                          for d in case.documents]}


@router.patch("/cases/{cid}")
def patch_case(cid: str, body: CasePatch,
               p: Principal = Depends(get_principal),
               db: Session = Depends(get_db), request: Request = None):
    case = _get_case(db, p.user, cid)
    changed: list[str] = []
    if body.title is not None:
        title = (body.title or "").strip()
        if not title:
            raise HTTPException(400, "Title cannot be empty")
        if title != case.title:
            case.title = title
            changed.append("title")
    for attr, val in (("assessment_year", body.assessment_year), ("pan", body.pan), ("section", body.section)):
        if val is None:
            continue
        cleaned = val.strip() or None
        if attr == "pan" and cleaned:
            cleaned = cleaned.upper()
        if cleaned != getattr(case, attr):
            setattr(case, attr, cleaned)
            changed.append(attr)
    if changed:
        db.commit()
        audit.log_event(db, action="assessment.case.edit", user_id=p.user.id, wing_id=p.user.wing_id,
                        resource_type="assessment_case", resource_id=str(case.id),
                        query_text=",".join(changed), **client_meta(request))
    return {**_case_out(case),
            "documents": [{"id": d.id, "filename": d.filename, "category": d.category, "pages": d.pages}
                          for d in case.documents]}


@router.delete("/cases/{cid}", status_code=204)
def delete_case(cid: str, p: Principal = Depends(get_principal),
                db: Session = Depends(get_db), request: Request = None):
    case = _get_case(db, p.user, cid)
    case_id_int = case.id

    active = db.scalar(select(AssessmentRun).where(AssessmentRun.case_id == case.id)
                       .order_by(desc(AssessmentRun.id)).limit(1))
    if active and active.status in ("queued", "running"):
        _cancel_run(db, active, user_id=p.user.id)

    for d in list(case.documents):
        if not d.minio_key:
            continue
        try:
            from app.services.storage import remove_object
            remove_object(d.minio_key)
        except Exception as e:
            log.warning("storage delete failed for %s: %s", d.minio_key, e)

    case = db.get(AssessmentCase, case_id_int)
    if case is None:
        return None
    case_title = case.title
    db.delete(case)
    db.commit()
    audit.log_event(db, action="assessment.case.delete", user_id=p.user.id, wing_id=p.user.wing_id,
                    resource_type="assessment_case", resource_id=str(case_id_int),
                    query_text=case_title, **client_meta(request))
    return None


