@router.post("/cases/{cid}/run")
def start_run(cid: str, p: Principal = Depends(get_principal),
              _quota: Principal = Depends(require_quota),
              db: Session = Depends(get_db), request: Request = None):
    case = _get_case(db, p.user, cid)
    if not case.documents:
        raise HTTPException(400, "Upload documents before running")
    run = AssessmentRun(case_id=case.id, created_by=p.user.id, status="queued")
    db.add(run); db.commit(); db.refresh(run)
    from app.ingestion.tasks import run_assessment_case
    async_result = run_assessment_case.delay(run.id)
    run.task_id = async_result.id
    db.commit()
    audit.log_event(db, action="assessment.run", user_id=p.user.id, wing_id=p.user.wing_id,
                    resource_type="assessment_case", resource_id=str(case.id), **client_meta(request))
    return _run_out(run)


def _cancel_run(db: Session, run: AssessmentRun, *, user_id: int) -> None:
    if run.status not in ("queued", "running"):
        return
    if run.task_id:
        try:
            from app.ingestion.tasks import celery_app
            celery_app.control.revoke(run.task_id, terminate=True, signal="SIGTERM")
        except Exception:
            pass
    from sqlalchemy import update as _sql_update
    db.execute(_sql_update(AssessmentRun).where(AssessmentRun.id == run.id)
               .values(status="error", error=f"Cancelled by user (uid={user_id})",
                       finished_at=datetime.now(timezone.utc)))
    db.execute(_sql_update(AssessmentCase).where(AssessmentCase.id == run.case_id,
                                                 AssessmentCase.status == "running")
               .values(status="error"))
    db.commit()
    db.expire_all()


@router.post("/runs/{rid}/cancel")
def cancel_run(rid: int, p: Principal = Depends(get_principal),
               db: Session = Depends(get_db), request: Request = None):
    run = db.get(AssessmentRun, rid)
    if not run:
        raise HTTPException(404, "Run not found")
    _get_case(db, p.user, run.case_id)
    _cancel_run(db, run, user_id=p.user.id)
    audit.log_event(db, action="assessment.run.cancel", user_id=p.user.id, wing_id=p.user.wing_id,
                    resource_type="assessment_run", resource_id=str(rid), **client_meta(request))
    return _run_out(run)


@router.post("/cases/{cid}/stop")
def stop_case(cid: str, p: Principal = Depends(get_principal),
              db: Session = Depends(get_db), request: Request = None):
    from sqlalchemy import update as _sql_update
    case = _get_case(db, p.user, cid)
    run = _latest_run(db, case.id)
    if not run:
        db.execute(_sql_update(AssessmentCase).where(AssessmentCase.id == case.id,
                                                     AssessmentCase.status == "running")
                   .values(status="new"))
        db.commit()
        raise HTTPException(404, "No run to stop")
    if run.status not in ("queued", "running"):
        target = "ready" if run.status == "done" else "error"
        db.execute(_sql_update(AssessmentCase).where(AssessmentCase.id == case.id,
                                                     AssessmentCase.status == "running")
                   .values(status=target))
        db.commit()
        db.expire_all()
        return _run_out(run)
    _cancel_run(db, run, user_id=p.user.id)
    audit.log_event(db, action="assessment.case.stop", user_id=p.user.id, wing_id=p.user.wing_id,
                    resource_type="assessment_case", resource_id=str(cid), **client_meta(request))
    return _run_out(run)


